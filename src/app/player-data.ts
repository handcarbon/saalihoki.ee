export const PORTAL_PLAYER_SEASON = '2025 / 2026';

const playersForLeague = (league: string, players: readonly PlayerSeed[]): PortalPlayer[] =>
  players.map(([name, team, games, goals, assists, isGoalie]) => ({
    name,
    team,
    position: isGoalie ? 'Väravavaht' : 'Mängija',
    season: PORTAL_PLAYER_SEASON,
    league,
    games,
    goals,
    assists
  }));

